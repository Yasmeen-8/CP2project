    private void savebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebtnActionPerformed
        if (empRadio.isSelected()) {
            if (fnInput.getText().trim().isEmpty()
                    || snInput.getText().trim().isEmpty()
                    || addressInput.getText().trim().isEmpty()
                    || phoneInput.getText().trim().isEmpty()
                    || salaryInput.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields before saving.");
                return;
            }
            try {
                currentEmployee.setName(fnInput.getText().trim());
                currentEmployee.setAddress(addressInput.getText().trim());
                currentEmployee.setPhoneNumber(Integer.parseInt(phoneInput.getText().trim()));
                currentEmployee.setSalary(Double.parseDouble(salaryInput.getText().trim()));
                StoreUsers.save();
                searchEmployee();
                hideEditSection();
                javax.swing.JOptionPane.showMessageDialog(this, "Employee updated successfully.");
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Phone and salary must be valid numbers.");
            }

        } else if (memberRadio.isSelected()) {
            if (fnInput.getText().trim().isEmpty()
                    || snInput.getText().trim().isEmpty()
                    || addressInput.getText().trim().isEmpty()
                    || phoneInput.getText().trim().isEmpty()
                    || DOBInput.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields before saving.");
                return;
            }
            try {
                currentMember.setName(fnInput.getText().trim());
                currentMember.setAddress(addressInput.getText().trim());
                currentMember.setPhoneNumber(Integer.parseInt(phoneInput.getText().trim()));
                currentMember.setDOB(DOBInput.getText().trim());
                StoreUsers.save();
                searchMember();
                hideEditSection();
                javax.swing.JOptionPane.showMessageDialog(this, "Member updated successfully.");
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Phone number must be a valid number.");
            }
        }
    }//GEN-LAST:event_savebtnActionPerformed

