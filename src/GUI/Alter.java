    //Upon clicking edit button, it checks if the textbox for search ID is empty or invalid, and if not it displays info to alter.
    private void editbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editbtnActionPerformed
        String id = IDinput.getText().trim();

        if (id.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter an ID first.");
            return;
        }
        if (empRadio.isSelected() && currentEmployee == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please search and find a valid employee first.");
            return;
        }
        if (memberRadio.isSelected() && currentMember == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please search and find a valid member first.");
            return;
        }

        if (empRadio.isSelected()) {
            fnInput.setText(currentEmployee.getName());
            snInput.setText("");
            addressInput.setText(currentEmployee.getAddress() != null ? currentEmployee.getAddress() : "");
            phoneInput.setText(String.valueOf(currentEmployee.getPhoneNumber()));
            salaryInput.setText(String.valueOf(currentEmployee.getSalary()));
            showEmpEditSection();
        } else if (memberRadio.isSelected()) {
            fnInput.setText(currentMember.getName());
            snInput.setText("");
            addressInput.setText(currentMember.getAddress() != null ? currentMember.getAddress() : "");
            phoneInput.setText(String.valueOf(currentMember.getPhoneNumber()));
            DOBInput.setText(currentMember.getDOB() != null ? currentMember.getDOB() : "");
            showMemberEditSection();
        }
    }//GEN-LAST:event_editbtnActionPerformed

